// S-CI-005: render the markdown table for the PR comment.
//
// Reads two JSON files: base (target branch) + head (PR), where each
// file is `{ "<asset path>": <size in bytes>, ... }` produced by
// `bundle-stats.mjs`. Output is a sticky-comment-friendly markdown
// table grouped by entry chunk, with +/- columns and a totals row.

import { readFileSync } from "node:fs";

const [baseFile, headFile] = process.argv.slice(2);
const base = JSON.parse(readFileSync(baseFile, "utf8"));
const head = JSON.parse(readFileSync(headFile, "utf8"));

function fmt(bytes) {
  if (bytes === undefined) return "—";
  if (Math.abs(bytes) < 1024) return `${bytes} B`;
  if (Math.abs(bytes) < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} kB`;
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

function sign(n) {
  if (n === 0) return "·";
  if (n > 0) return `+${fmt(n)} 🔺`;
  return `${fmt(n)} 🟢`;
}

const all = new Set([...Object.keys(base), ...Object.keys(head)]);
const rows = [...all]
  .map((path) => ({
    path,
    base: base[path],
    head: head[path],
    delta: (head[path] ?? 0) - (base[path] ?? 0),
  }))
  .filter((r) => r.delta !== 0 || r.base === undefined || r.head === undefined)
  .sort((a, b) => Math.abs(b.delta) - Math.abs(a.delta));

const totalBase = Object.values(base).reduce((a, b) => a + b, 0);
const totalHead = Object.values(head).reduce((a, b) => a + b, 0);

let out = "";
out += `### Bundle size report\n\n`;
out += `Total: **${fmt(totalHead)}** (base **${fmt(totalBase)}**, ${sign(totalHead - totalBase)})\n\n`;

if (rows.length === 0) {
  out += `_No per-asset deltas — total may have shifted from rounding._\n`;
} else {
  out += `| Asset | Base | Head | Δ |\n|---|---:|---:|---:|\n`;
  for (const r of rows.slice(0, 30)) {
    out += `| \`${r.path}\` | ${fmt(r.base)} | ${fmt(r.head)} | ${sign(r.delta)} |\n`;
  }
  if (rows.length > 30) out += `\n_…and ${rows.length - 30} more, see the artifact for the full list._\n`;
}

out += `\n<sub>Generated by S-CI-005. Hard ceilings live in \`scripts/perf/check-bundle.mjs\`.</sub>\n`;

process.stdout.write(out);
